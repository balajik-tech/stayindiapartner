import 'package:stayindia_owner/features/profile/domain/entities/hostel.dart';
import 'package:stayindia_owner/features/property_setup/domain/repositories/property_setup_repository.dart';

class SetupPropertyUseCase {
  final PropertySetupRepository repository;

  SetupPropertyUseCase(this.repository);

  Future<Hostel> execute({
    String? hostelId,
    required String name,
    required String address,
    required int floors,
    required List<String> amenities,
    required List<Map<String, dynamic>> rooms,
    List<Map<String, dynamic>>? roomCategories,
    required Map<String, dynamic> masterPricing,
    double? lat,
    double? lng,
    required String area,
    required String city,
    required String state,
    required String hostelType,
    required List<String> images,
    String? pincode,
    String? contactNumber,
    String? contactEmail,
    String? description,
    String? propertyTag,
    String? district,
    String? village,
    String? foodLicense,
    String? hostelLicense,
    String? tradeLicense,
    String? fireSafety,
    String? policeNoc,
    String? shopsEstablishment,
    String? gstRegistration,
    String? healthSanitation,
    String? utilityBill,
    String? pollutionNoc,
    String? residentVerification,
  }) {
    return repository.setupCompleteProperty(
      hostelId: hostelId,
      name: name,
      address: address,
      floors: floors,
      amenities: amenities,
      rooms: rooms,
      roomCategories: roomCategories,
      masterPricing: masterPricing,
      lat: lat,
      lng: lng,
      area: area,
      city: city,
      state: state,
      hostelType: hostelType,
      images: images,
      pincode: pincode,
      contactNumber: contactNumber,
      contactEmail: contactEmail,
      description: description,
      propertyTag: propertyTag,
      district: district,
      village: village,
      foodLicense: foodLicense,
      hostelLicense: hostelLicense,
      tradeLicense: tradeLicense,
      fireSafety: fireSafety,
      policeNoc: policeNoc,
      shopsEstablishment: shopsEstablishment,
      gstRegistration: gstRegistration,
      healthSanitation: healthSanitation,
      utilityBill: utilityBill,
      pollutionNoc: pollutionNoc,
      residentVerification: residentVerification,
    );
  }
}
